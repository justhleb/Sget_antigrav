"""
Скрипт запуска многокритериальной оптимизации парка трамваев с помощью NSGA-II.

Создает папку вывода с уникальным временным штампом, 
импортирует функцию run_nsga2 из модуля optimizer и запускает процесс 
поиска оптимального распределения трамваев по маршрутам 20, 48 и 55.
"""

from optimizer import run_nsga2, N_MAX, ROUTE_PAIRS
import os
from datetime import datetime

# Генерируем временной штамп для создания уникальной папки запуска
ts = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
# Путь, куда будут сохранены Парето-оптимальные решения и их визуализация
out_dir = os.path.join("outputs", f"run_{ts}", "nsga2")

# Запуск алгоритма оптимизации NSGA-II
run_nsga2(
    n_max=60,           # Тестовый прогон: 60 трамваев (создает умеренный дефицит)
    pop_size=40,        # Размер популяции (40 вариантов распределения)
    n_gen=15,           # Количество поколений генетического алгоритма (15 генераций)
    seed=42,            # Сид случайных чисел для воспроизводимости результатов
    out_dir=out_dir,    # Папка вывода
)
